#!/usr/bin/env python3
"""Generates src/tables.rs: one 256-entry byte-class table, with each bit
proven equal to its spec predicate (by compute)."""
import os

# (name, Verus spec predicate over c: u8, Python predicate)
BITS = [
    ("C0", "in_c0_control_set(c)", lambda c: c < 0x20 or c > 0x7E),
    ("FRAGMENT", "in_fragment_set(c)", None),
    ("QUERY", "in_query_set(c)", None),
    ("SPECIAL_QUERY", "in_special_query_set(c)", None),
    ("PATH", "in_path_set(c)", None),
    ("USERINFO", "in_userinfo_set(c)", None),
    ("TAB_NEWLINE", "is_ascii_tab_or_newline(c)", lambda c: c in (9, 10, 13)),
    ("PATH_STOP", "c == 0x2F || c == 0x3F || c == 0x23", lambda c: c in b"/?#"),
    ("BACKSLASH", "c == 0x5C", lambda c: c == 0x5C),
    ("AUTHORITY_STOP", "c == 0x40 || c == 0x2F || c == 0x3F || c == 0x23", lambda c: c in b"@/?#"),
    ("HOST_STOP", "c == 0x3A || c == 0x2F || c == 0x3F || c == 0x23 || c == 0x5B || c == 0x5D",
     lambda c: c in b":/?#[]"),
    ("HASH", "c == 0x23", lambda c: c == 0x23),
    ("DOMAIN_SLOW", "c >= 0x80 || is_ascii_upper_alpha(c) || is_forbidden_domain_code_point(c)", None),
    ("PATH_FAST", "in_path_set(c) || c == 0x2E || c == 0x25 || c == 0x5C", None),
]

def c0(c): return c < 0x20 or c > 0x7E
def frag(c): return c0(c) or c in b' "<>`'
def query(c): return c0(c) or c in b' "#<>'
def squery(c): return query(c) or c == ord("'")
def path(c): return query(c) or c in b'?^`{}'
def user(c): return path(c) or c in b'/:;=@|' or (0x5B <= c <= 0x5D)
def forbidden_host(c): return c in (0, 9, 10, 13) or c in b' #/:<>?@[\\]^|'
def forbidden_domain(c): return forbidden_host(c) or c <= 0x1F or c == 0x25 or c == 0x7F
fns = {"FRAGMENT": frag, "QUERY": query, "SPECIAL_QUERY": squery, "PATH": path, "USERINFO": user,
       "PATH_FAST": lambda c: path(c) or c in b'.%\\',
       "DOMAIN_SLOW": lambda c: c >= 0x80 or 0x41 <= c <= 0x5A or forbidden_domain(c)}
BITS = [(n, s, f or fns[n]) for (n, s, f) in BITS]

table = []
for c in range(256):
    v = 0
    for k, (_, _, f) in enumerate(BITS):
        if f(c):
            v |= 1 << k
    table.append(v)

out = []
out.append("//! Byte classes: one table load answers \"is this byte in set X\" for")
out.append("//! every set the parser scans for. Generated by tools/gen_tables.py; each")
out.append("//! bit is proven equal to its spec predicate.")
out.append("use crate::spec::*;")
out.append("use vstd::compute::RangeAll;")
out.append("use vstd::prelude::*;")
out.append("")
out.append("verus! {")
out.append("")
for k, (n, _, _) in enumerate(BITS):
    out.append(f"pub const {n}: u16 = {1 << k};")
out.append("")
rows = []
for i in range(0, 256, 16):
    rows.append("    " + ", ".join(str(v) for v in table[i:i + 16]) + ",")
out.append("pub const CLS: [u16; 256] = [")
out.extend(rows)
out.append("];")
out.append("")
out.append("/// The spec predicate behind each class bit.")
out.append("pub open spec fn cls_pred(bit: u16, c: u8) -> bool {")
first = True
for k, (n, s, _) in enumerate(BITS):
    kw = "if" if first else "} else if"
    out.append(f"    {kw} bit == {n} {{")
    out.append(f"        {s}")
    first = False
out.append("    } else {")
out.append("        false")
out.append("    }")
out.append("}")
out.append("")
out.append("pub open spec fn cls_has(c: u8, bit: u16) -> bool {")
out.append("    CLS@[c as int] & bit != 0")
out.append("}")
out.append("")
for k, (n, s, _) in enumerate(BITS):
    ln = n.lower()
    out.append(f"proof fn lemma_cls_{ln}()")
    out.append("    ensures")
    out.append(f"        forall|c: u8| #[trigger] cls_has(c, {n}) == cls_pred({n}, c),")
    out.append("{")
    out.append(f"    let p = |i: int| (CLS@[i] & {n} != 0) == cls_pred({n}, i as u8);")
    out.append(f"    assert((0..256int).all_spec(|i: int| (CLS@[i] & {n} != 0) == cls_pred({n}, i as u8))) by (compute_only);")
    out.append(f"    vstd::compute::all_spec_ensures(0..256int, p);")
    out.append(f"    assert forall|c: u8| #[trigger] cls_has(c, {n}) == cls_pred({n}, c) by {{")
    out.append("        assert((c as int) as u8 == c);")
    out.append("        assert(p(c as int));")
    out.append("    }")
    out.append("}")
    out.append("")
out.append("/// Every class bit agrees with its predicate.")
out.append("pub proof fn lemma_cls()")
out.append("    ensures")
for n, _, _ in BITS:
    out.append(f"        forall|c: u8| #[trigger] cls_has(c, {n}) == cls_pred({n}, c),")
out.append("{")
for n, _, _ in BITS:
    out.append(f"    lemma_cls_{n.lower()}();")
out.append("}")
out.append("")
out.append("/// The byte's class bits.")
out.append("#[inline(always)]")
out.append("pub fn cls(c: u8) -> (r: u16)")
out.append("    ensures")
out.append("        r == CLS@[c as int],")
out.append("{")
out.append("    CLS[c as usize]")
out.append("}")
out.append("")
out.append("} // verus!")
path = os.path.join(os.path.dirname(__file__), "..", "src", "tables.rs")
open(path, "w").write("\n".join(out) + "\n")
