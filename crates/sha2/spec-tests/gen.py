"""Writes src/cases.rs: for each message of NIST's CAVP SHA-2 ShortMsg
response files (SHA-224, SHA-256, SHA-384, SHA-512, SHA-512/224 and
SHA-512/256), a proof function asserting that the spec's hash of it is the
digest NIST gives, proved by evaluation.

ShortMsg has every message length from 0 to one block, in bytes (65 for the
SHA-256 family, 129 for SHA-512's), so padding is checked at every length,
including the lengths that need a second block. SHA-224 and SHA-256 are
run on all of them. The evaluator takes about 12 seconds per SHA-256 block
but about 6 minutes per SHA-512 block, so the four 64-bit hashes are run
on the empty message only: that checks their initial values, rounds,
padding and truncation, but not their padding at other lengths. LongMsg
(up to 100 blocks) and the Monte Carlo tests (100,000 hashes each) are
left out too, for the same reason.
"""
import os, sys

suite, out = sys.argv[1], sys.argv[2]
FILES = [
    ("SHA224ShortMsg.rsp", "verilith_sha2::spec::sha224", "compress", "spec"),
    ("SHA256ShortMsg.rsp", "verilith_sha2::spec::sha256", "compress", "spec"),
    ("SHA384ShortMsg.rsp", "verilith_sha2::spec512::sha384", "compress", "spec512"),
    ("SHA512ShortMsg.rsp", "verilith_sha2::spec512::sha512", "compress", "spec512"),
    ("SHA512_224ShortMsg.rsp", "verilith_sha2::spec512::sha512_224", "compress", "spec512"),
    ("SHA512_256ShortMsg.rsp", "verilith_sha2::spec512::sha512_256", "compress", "spec512"),
]

def seq(b):
    return "seq![" + ", ".join("%du8" % x for x in b) + "]" if b else "Seq::<u8>::empty()"

lines = [
    "// @generated by gen.py from NIST's CAVP SHA-2 vectors. Do not edit.",
    "use vstd::prelude::*;",
    "",
    "verus! {",
    "",
]
n = 0
for fname, fn, opaque, module in FILES:
    cases = []
    cur = {}
    for line in open(os.path.join(suite, fname)):
        line = line.strip()
        if " = " in line:
            k, v = line.split(" = ", 1)
            cur[k] = v
            if k == "MD":
                cases.append(cur)
                cur = {}
    assert len(cases) in (65, 129), (fname, len(cases))
    if module == "spec512":
        cases = [c for c in cases if c["Len"] == "0"]
    for c in cases:
        ln = int(c["Len"])
        assert ln % 8 == 0
        msg = bytes.fromhex(c["Msg"])[: ln // 8]
        md = bytes.fromhex(c["MD"])
        n += 1
        name = fname[:-4].lower()
        lines.append(f"// {fname}, Len = {ln}")
        lines.append(f"proof fn c{n:03d}_{name}_{ln // 8}() {{")
        # The compression function is opaque to the proofs about whole
        # messages; revealing it lets the evaluator run it.
        lines.append(f"    reveal(verilith_sha2::{module}::{opaque});")
        lines.append(f"    assert({fn}({seq(msg)}) == {seq(md)}) by (compute_only);")
        lines.append("}")
        lines.append("")
lines.append("} // verus!")
open(os.path.join(out, "cases.rs"), "w").write("\n".join(lines) + "\n")
open(os.path.join(out, "cases.count"), "w").write(f"{n}\n")
print(f"{n} cases")
