#!/usr/bin/env python3
"""Generates src/stable.rs: RFC 9204's static table (Appendix A).

Reads it from two independent sources and fails unless they agree entry
for entry: the RFC's own Markdown source (quicwg/base-drafts rfc9204.md)
and ls-qpack (lsqpack.c). tests/tables.rs checks the result again against
a few entries quoted from the RFC.

    tools/gen_tables.py RFC9204_MD LSQPACK_C src/stable.rs
"""
import re
import sys


def rfc(path):
    t = open(path).read()
    t = t[t.index("# Static Table\n"):]
    t = t[:t.index('{: title="Static Table"}')]
    rows = []
    for line in t.splitlines():
        m = re.match(r"^\| (\d+) +\| (\S+) +\| (.*?) *\|$", line)
        if m:
            v = m.group(3).replace("\\*", "*").replace("\\'", "'")
            assert int(m.group(1)) == len(rows), line
            rows.append((m.group(2), v))
    return rows


def lsqpack(path):
    t = open(path).read()
    t = t[t.index("static_table[] =\n{"):]
    t = t[:t.index("};")]
    rows = []
    for n, v, nl, vl in re.findall(r'\{"([^"]*)",\s*"((?:[^"\\]|\\.)*)",\s*(\d+),\s*(\d+),\}', t):
        v = v.encode().decode("unicode_escape")
        assert len(n) == int(nl) and len(v) == int(vl), (n, v)
        rows.append((n, v))
    return rows


def main():
    a = rfc(sys.argv[1])
    b = lsqpack(sys.argv[2])
    assert len(a) == 99 and a == b, "static tables disagree"
    with open(sys.argv[3], "w") as f:
        f.write("// Generated by tools/gen_tables.py from RFC 9204's source and ls-qpack,\n")
        f.write("// which agree entry for entry. Do not edit.\n//\n")
        f.write("// RFC 9204 Appendix A: the static table, entries 0 to 98.\n")
        f.write("pub const STATIC: [(&[u8], &[u8]); 99] = [\n")
        for n, v in a:
            f.write('    (b"%s", b"%s"),\n' % (n, v))
        f.write("];\n")


main()
