#!/usr/bin/env python3
"""Generates src/x86.rs (the trusted intrinsic specifications) and, given a
second path, src/safe.rs (safe wrappers with the same specifications), and,
given a third, src/x86_emu.rs (the same specifications on `crate::emu`, for
targets other than x86-64) from the table below.

    python3 tools/gen_x86.py src/x86.rs src/safe.rs src/x86_emu.rs
 Each row: (intrinsic, const generic or None, params, result,
feature, ensures). Views: B=b128/b256 bytes, U16, U32, U64 lanes."""
import sys

def views(w):
    if w == 128:
        return dict(B="b128", U16="u16x8", U32="u32x4", U64="u64x2", N8=16, N16=8, N32=4, N64=2, T="__m128i", P="_mm_", F=None)
    return dict(B="b256", U16="u16x16", U32="u32x8", U64="u64x4", N8=32, N16=16, N32=8, N64=4, T="__m256i", P="_mm256_", F="avx2")

# (suffix, const, params(list of (name, type-key)), result type-key, extra feature for 128, ensures template)
# type keys: V = vector of this width; i8,i16,i32,i64 = scalars.
BIN = [
 ("add_epi8",  "{B}(r) == add8({B}(a), {B}(b))"),
 ("sub_epi8",  "{B}(r) == sub8({B}(a), {B}(b))"),
 ("adds_epu8", "{B}(r) == adds_u8({B}(a), {B}(b))"),
 ("subs_epu8", "{B}(r) == subs_u8({B}(a), {B}(b))"),
 ("adds_epi8", "{B}(r) == adds_s8({B}(a), {B}(b))"),
 ("subs_epi8", "{B}(r) == subs_s8({B}(a), {B}(b))"),
 ("subs_epu16", "{U16}(r) == subs_u16({U16}(a), {U16}(b))"),
 ("min_epu8",  "{B}(r) == min_u8({B}(a), {B}(b))"),
 ("max_epu8",  "{B}(r) == max_u8({B}(a), {B}(b))"),
 ("avg_epu8",  "{B}(r) == avg_u8({B}(a), {B}(b))"),
 ("cmpeq_epi8", "{B}(r) == cmpeq8({B}(a), {B}(b))"),
 ("cmpgt_epi8", "{B}(r) == cmpgt_s8({B}(a), {B}(b))"),
 ("add_epi16", "{U16}(r) == add16({U16}(a), {U16}(b))"),
 ("sub_epi16", "{U16}(r) == sub16({U16}(a), {U16}(b))"),
 ("mullo_epi16", "{U16}(r) == mullo16({U16}(a), {U16}(b))"),
 ("mulhi_epi16", "{U16}(r) == mulhi_s16({U16}(a), {U16}(b))"),
 ("mulhi_epu16", "{U16}(r) == mulhi_u16({U16}(a), {U16}(b))"),
 ("cmpeq_epi16", "{U16}(r) == cmpeq16({U16}(a), {U16}(b))"),
 ("madd_epi16", "{U32}(r) == madd16({U16}(a), {U16}(b))"),
 ("add_epi32", "{U32}(r) == add32({U32}(a), {U32}(b))"),
 ("sub_epi32", "{U32}(r) == sub32({U32}(a), {U32}(b))"),
 ("cmpeq_epi32", "{U32}(r) == cmpeq32({U32}(a), {U32}(b))"),
 ("cmpgt_epi32", "{U32}(r) == cmpgt_s32({U32}(a), {U32}(b))"),
 ("add_epi64", "{U64}(r) == add64({U64}(a), {U64}(b))"),
 ("sad_epu8", "{U64}(r) == sad8({B}(a), {B}(b))"),
 ("unpacklo_epi8", "{B}(r) == unpacklo8_lanes({B}(a), {B}(b))"),
 ("unpackhi_epi8", "{B}(r) == unpackhi8_lanes({B}(a), {B}(b))"),
 ("unpacklo_epi16", "{U16}(r) == unpacklo16_lanes({U16}(a), {U16}(b))"),
 ("unpackhi_epi16", "{U16}(r) == unpackhi16_lanes({U16}(a), {U16}(b))"),
 ("unpacklo_epi32", "{U32}(r) == unpacklo32_lanes({U32}(a), {U32}(b))"),
 ("unpackhi_epi32", "{U32}(r) == unpackhi32_lanes({U32}(a), {U32}(b))"),
 ("unpacklo_epi64", "{U64}(r) == unpacklo64_lanes({U64}(a), {U64}(b))"),
 ("unpackhi_epi64", "{U64}(r) == unpackhi64_lanes({U64}(a), {U64}(b))"),
 ("packus_epi16", "{B}(r) == packus16_lanes({U16}(a), {U16}(b))"),
 ("packs_epi16", "{B}(r) == packs16_lanes({U16}(a), {U16}(b))"),
 ("packs_epi32", "{U16}(r) == packs32_lanes({U32}(a), {U32}(b))"),
]
# 128-bit ops needing more than SSE2
SSE_FEAT = {"shuffle_epi8": "ssse3", "maddubs_epi16": "ssse3", "alignr_epi8": "ssse3", "blendv_epi8": "sse41"}
BIN_EXTRA = [
 ("shuffle_epi8", "{B}(r) == shuffle8_lanes({B}(a), {B}(b))"),
 ("maddubs_epi16", "{U16}(r) == maddubs({B}(a), {B}(b))"),
]
# bitwise ops have width-specific names
BITW = [("and", "and8"), ("or", "or8"), ("xor", "xor8"), ("andnot", "andnot8")]
IMM = [
 # (suffix, const name, constraint, ensures)
 ("srli_epi16", "IMM8", "0 <= IMM8 <= 255", "{U16}(r) == srli16({U16}(a), IMM8 as int)"),
 ("slli_epi16", "IMM8", "0 <= IMM8 <= 255", "{U16}(r) == slli16({U16}(a), IMM8 as int)"),
 ("srai_epi16", "IMM8", "0 <= IMM8 <= 255", "{U16}(r) == srai16({U16}(a), IMM8 as int)"),
 ("srli_epi32", "IMM8", "0 <= IMM8 <= 255", "{U32}(r) == srli32({U32}(a), IMM8 as int)"),
 ("srai_epi32", "IMM8", "0 <= IMM8 <= 255", "{U32}(r) == srai32({U32}(a), IMM8 as int)"),
 ("slli_epi32", "IMM8", "0 <= IMM8 <= 255", "{U32}(r) == slli32({U32}(a), IMM8 as int)"),
 ("srli_epi64", "IMM8", "0 <= IMM8 <= 255", "{U64}(r) == srli64({U64}(a), IMM8 as int)"),
 ("slli_epi64", "IMM8", "0 <= IMM8 <= 255", "{U64}(r) == slli64({U64}(a), IMM8 as int)"),
 ("shuffle_epi32", "IMM8", "0 <= IMM8 <= 255", "{U32}(r) == shuffle32_lanes({U32}(a), IMM8 as int)"),
]

out = []
P = out.append
sout = []
SP = sout.append
SP("""//! Safe wrappers for the specified x86 SIMD intrinsics (TRUSTED).
//!
//! GENERATED by `tools/gen_x86.py`; edit the table there, not this file.
//!
//! The `core::arch::x86_64` intrinsics carry `#[target_feature]`, so a
//! function that calls them must carry it too, and Verus rejects that
//! attribute on verified code (verus-lang/verus#3362). Each function here
//! has the name, `requires` and `ensures` of one `assume_specification` in
//! `crate::x86`, and its body is the single call to that intrinsic. The
//! `requires` include the CPU-feature predicate, so the call is reached
//! only after detection. Callers inline these into a `#[target_feature]`
//! trampoline, so the generated code is the intrinsic's.
//!
//! Everything else in `core::arch::x86_64` (the vector types, and
//! intrinsics without a specification) is re-exported unchanged; the
//! definitions below shadow that glob, so `crate::arch` exports these.
#![allow(unused_imports, unused_unsafe, non_snake_case)]
pub use core::arch::x86_64::*;
use crate::cpu::*;
use crate::lanes::*;
use crate::ops::*;
#[cfg(verus_only)]
use crate::x86::{half128, perm2x128};
use vstd::prelude::*;

verus! {
""")
P("""//! Specifications of the x86 SIMD intrinsics (TRUSTED).
//!
//! GENERATED by `tools/gen_x86.py`; edit the table there, not this file.
//!
//! Each `assume_specification` states what one `core::arch::x86_64`
//! intrinsic computes, in terms of the lane functions in `crate::ops`. Verus
//! takes these on trust. They are checked, not proven: `tests/difftest.rs`
//! runs every intrinsic here against the verified reference implementation
//! of its spec (`crate::refs`) on random and edge-case inputs.
//!
//! Intrinsics beyond SSE2 require the CPU-feature predicate from
//! `crate::cpu`, so verified code reaches them only after detection.
#![allow(unused_imports)]
use crate::cpu::*;
use crate::lanes::*;
use crate::ops::*;
use core::arch::x86_64::*;
use vstd::prelude::*;

verus! {
""")

def spec(name, consts, params, ret, req, ens):
    g = ""
    if consts:
        g = "<" + ", ".join(f"const {c}: i32" for c in consts) + ">"
    turbofish = ("::<" + ", ".join(consts) + ">") if consts else ""
    ps = ", ".join(f"{n}: {t}" for n, t in params)
    P(f"pub assume_specification{g}[ core::arch::x86_64::{name}{turbofish} ]({ps}) -> (r: {ret})")
    if req:
        P("    requires")
        for q in req:
            P(f"        {q},")
    P("    ensures")
    for e in ens:
        P(f"        {e},")
    P(";\n")
    SP(f"/// [`{name}`](core::arch::x86_64::{name}) as a safe function, with the")
    SP("/// specification Verus checks callers against:")
    SP("///")
    SP("/// ```text")
    for q in req:
        SP(f"/// requires {q}")
    for e in ens:
        SP(f"/// ensures  {e}")
    SP("/// ```")
    SP("#[verifier::external_body]\n#[inline(always)]")
    SP(f"pub fn {name}{g}({ps}) -> (r: {ret})")
    if req:
        SP("    requires")
        for q in req:
            SP(f"        {q},")
    SP("    ensures")
    for e in ens:
        SP(f"        {e},")
    args = ", ".join(n for n, _ in params)
    SP("{")
    SP(f"    unsafe {{ core::arch::x86_64::{name}{turbofish}({args}) }}")
    SP("}\n")

for w in (128, 256):
    v = views(w)
    T = v["T"]
    P(f"// {'-'*75}\n// {w}-bit\n// {'-'*75}\n")
    for suf, ens in BIN + BIN_EXTRA:
        req = []
        if v["F"]: req.append("avx2()")
        elif suf in SSE_FEAT: req.append(SSE_FEAT[suf] + "()")
        spec(v["P"] + suf, None, [("a", T), ("b", T)], T, req, [ens.format(**v)])
    for op, f in BITW:
        nm = (f"_mm_{op}_si128" if w == 128 else f"_mm256_{op}_si256")
        spec(nm, None, [("a", T), ("b", T)], T, ["avx2()"] if v["F"] else [], [f"{v['B']}(r) == {f}({v['B']}(a), {v['B']}(b))"])
    # blendv
    spec(v["P"] + "blendv_epi8", None, [("a", T), ("b", T), ("mask", T)], T, ["avx2()" if v["F"] else "sse41()"],
         [f"{v['B']}(r) == blendv8({v['B']}(a), {v['B']}(b), {v['B']}(mask))"])
    for suf, c, cons, ens in IMM:
        spec(v["P"] + suf, [c], [("a", T)], T, ([cons] + (["avx2()"] if v["F"] else [])), [ens.format(**v)])
    # byte shifts / alignr
    bsl = "_mm_slli_si128" if w == 128 else "_mm256_bslli_epi128"
    bsr = "_mm_srli_si128" if w == 128 else "_mm256_bsrli_epi128"
    req = ["0 <= IMM8 <= 255"] + (["avx2()"] if v["F"] else [])
    spec(bsl, ["IMM8"], [("a", T)], T, req, [f"{v['B']}(r) == bslli_lanes({v['B']}(a), IMM8 as int)"])
    spec(bsr, ["IMM8"], [("a", T)], T, req, [f"{v['B']}(r) == bsrli_lanes({v['B']}(a), IMM8 as int)"])
    spec(v["P"] + "alignr_epi8", ["IMM8"], [("a", T), ("b", T)], T,
         ["0 <= IMM8 <= 255"] + (["avx2()"] if v["F"] else ["ssse3()"]),
         [f"{v['B']}(r) == alignr_lanes({v['B']}(a), {v['B']}(b), IMM8 as int)"])
    # movemask
    spec(v["P"] + "movemask_epi8", None, [("a", T)], "i32", ["avx2()"] if v["F"] else [],
         [f"u32_of_i32(r) as nat == movemask({v['B']}(a))"])
    # constructors
    rq = ["avx2()"] if v["F"] else []
    spec(v["P"] + "setzero_si" + str(w), None, [], T, ["avx2()"] if v["F"] else [], [f"{v['B']}(r) == splat8(0u8, {v['N8']})"])
    spec(v["P"] + "set1_epi8", None, [("x", "i8")], T, rq, [f"{v['B']}(r) == splat8(u8_of_i8(x), {v['N8']})"])
    spec(v["P"] + "set1_epi16", None, [("x", "i16")], T, rq, [f"{v['U16']}(r) == splat16(u16_of_i16(x), {v['N16']})"])
    spec(v["P"] + "set1_epi32", None, [("x", "i32")], T, rq, [f"{v['U32']}(r) == splat32(u32_of_i32(x), {v['N32']})"])
    spec(v["P"] + "set1_epi64x", None, [("x", "i64")], T, rq, [f"{v['U64']}(r) == splat64(u64_of_i64(x), {v['N64']})"])
    n = v["N32"]
    spec(v["P"] + "setr_epi32", None, [(f"e{i}", "i32") for i in range(n)], T, rq,
         [f"{v['U32']}(r) == seq![" + ", ".join(f"u32_of_i32(e{i})" for i in range(n)) + "]"])
    n = v["N8"]
    spec(v["P"] + "setr_epi8", None, [(f"e{i}", "i8") for i in range(n)], T, rq,
         [f"{v['B']}(r) == seq![" + ", ".join(f"u8_of_i8(e{i})" for i in range(n)) + "]"])

# 128-bit scalar moves
spec("_mm_cvtsi32_si128", None, [("x", "i32")], "__m128i", [], ["u32x4(r) == seq![u32_of_i32(x), 0u32, 0u32, 0u32]"])
spec("_mm_cvtsi128_si32", None, [("a", "__m128i")], "i32", [], ["u32_of_i32(r) == u32x4(a)[0]"])
spec("_mm_cvtsi64_si128", None, [("x", "i64")], "__m128i", [], ["u64x2(r) == seq![u64_of_i64(x), 0u64]"])
spec("_mm_cvtsi128_si64", None, [("a", "__m128i")], "i64", [], ["u64_of_i64(r) == u64x2(a)[0]"])
# 256 <-> 128
spec("_mm256_castsi256_si128", None, [("a", "__m256i")], "__m128i", ["avx2()"], ["b128(r) == b256(a).subrange(0, 16)"])
spec("_mm256_extracti128_si256", ["IMM1"], [("a", "__m256i")], "__m128i", ["avx2()", "IMM1 == 0 || IMM1 == 1"],
     ["b128(r) == b256(a).subrange(16 * IMM1, 16 * IMM1 + 16)"])
spec("_mm256_set_m128i", None, [("hi", "__m128i"), ("lo", "__m128i")], "__m256i", ["avx2()"], ["b256(r) == b128(lo) + b128(hi)"])
spec("_mm256_permutevar8x32_epi32", None, [("a", "__m256i"), ("idx", "__m256i")], "__m256i", ["avx2()"],
     ["u32x8(r) == permvar32(u32x8(a), u32x8(idx))"])
spec("_mm256_permute2x128_si256", ["IMM8"], [("a", "__m256i"), ("b", "__m256i")], "__m256i", ["avx2()", "0 <= IMM8 <= 255"],
     ["b256(r) == perm2x128(b256(a), b256(b), IMM8 as int)"])

spec("_mm_setr_epi16", None, [(f"e{i}", "i16") for i in range(8)], "__m128i", [],
     ["u16x8(r) == seq![" + ", ".join(f"u16_of_i16(e{i})" for i in range(8)) + "]"])
spec("_mm256_broadcastsi128_si256", None, [("a", "__m128i")], "__m256i", ["avx2()"], ["b256(r) == b128(a) + b128(a)"])
spec("_mm256_testz_si256", None, [("a", "__m256i"), ("b", "__m256i")], "i32", ["avx2()"],
     ["r == 0 || r == 1", "(r == 1) <==> (forall|i: int| 0 <= i < 32 ==> #[trigger] and8(b256(a), b256(b))[i] == 0u8)"])
# Carry-less multiply of the low quadwords; the low half of the product.
spec("_mm_clmulepi64_si128", ["IMM8"], [("a", "__m128i"), ("b", "__m128i")], "__m128i", ["pclmul()", "IMM8 == 0"],
     ["u64x2(r)[0] == clmul_lo(u64x2(a)[0], u64x2(b)[0], 64)"])

# 128-bit only, used by the SSE backend of the NEON wrappers (`crate::wasm_x86`).
spec("_mm_abs_epi16", None, [("a", "__m128i")], "__m128i", ["ssse3()"], ["u16x8(r) == abs16(u16x8(a))"])
spec("_mm_adds_epu16", None, [("a", "__m128i"), ("b", "__m128i")], "__m128i", [], ["u16x8(r) == adds_u16(u16x8(a), u16x8(b))"])
spec("_mm_max_epu16", None, [("a", "__m128i"), ("b", "__m128i")], "__m128i", ["sse41()"], ["u16x8(r) == max_u16(u16x8(a), u16x8(b))"])
spec("_mm_mullo_epi32", None, [("a", "__m128i"), ("b", "__m128i")], "__m128i", ["sse41()"], ["u32x4(r) == mullo32(u32x4(a), u32x4(b))"])
# Shifts by the count in the low 64 bits of `count`, stated for counts below
# the lane width (the only ones these specs allow).
spec("_mm_sll_epi16", None, [("a", "__m128i"), ("count", "__m128i")], "__m128i", ["u64x2(count)[0] < 16"],
     ["u16x8(r) == slli16(u16x8(a), u64x2(count)[0] as int)"])
spec("_mm_sra_epi16", None, [("a", "__m128i"), ("count", "__m128i")], "__m128i", ["u64x2(count)[0] < 16"],
     ["u16x8(r) == srai16(u16x8(a), u64x2(count)[0] as int)"])
spec("_mm_sll_epi32", None, [("a", "__m128i"), ("count", "__m128i")], "__m128i", ["u64x2(count)[0] < 32"],
     ["u32x4(r) == slli32(u32x4(a), u64x2(count)[0] as int)"])
spec("_mm_sra_epi32", None, [("a", "__m128i"), ("count", "__m128i")], "__m128i", ["u64x2(count)[0] < 32"],
     ["u32x4(r) == srai32(u32x4(a), u64x2(count)[0] as int)"])

P("/// The 16-byte half selected by `sel` (0, 1: halves of `a`; 2, 3: of\n/// `b`; bit 3 zeroes it), as `vperm2i128` picks each half.")
P("""pub open spec fn half128(a: Seq<u8>, b: Seq<u8>, sel: int) -> Seq<u8> {
    if sel % 16 >= 8 {
        splat8(0u8, 16)
    } else if sel % 4 == 0 {
        a.subrange(0, 16)
    } else if sel % 4 == 1 {
        a.subrange(16, 32)
    } else if sel % 4 == 2 {
        b.subrange(0, 16)
    } else {
        b.subrange(16, 32)
    }
}

pub open spec fn perm2x128(a: Seq<u8>, b: Seq<u8>, imm: int) -> Seq<u8> {
    half128(a, b, imm % 16) + half128(a, b, imm / 16)
}
""")
P("} // verus!")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
SP("} // verus!")
if len(sys.argv) > 2:
    open(sys.argv[2], "w").write("\n".join(sout) + "\n")

# The same specifications, stated of the portable emulation in `crate::emu`
# (what `crate::arch` is off x86-64), so code that names x86 intrinsics also
# verifies on AArch64 and other targets. Only the target of each
# `assume_specification` and the header differ from x86.rs.
if len(sys.argv) > 3:
    head = """//! Specifications of the portable x86 emulation (TRUSTED, off x86-64).
//!
//! GENERATED by `tools/gen_x86.py`; edit the table there, not this file.
//!
//! Off x86-64, `crate::arch` is `crate::emu`, and this file is `crate::x86`:
//! each `assume_specification` states what one `crate::emu` function
//! computes, exactly as `src/x86.rs` states it of the `core::arch::x86_64`
//! intrinsic of the same name, so code written against these specifications
//! verifies on every target. `crate::emu` is ordinary unverified Rust;
//! `tests/emu.rs` checks every function against the CPU instruction on
//! x86-64, and `tests/difftest.rs` checks the CPU against the verified
//! reference implementations in `crate::refs`.
//!
//! Intrinsics beyond SSE2 require the CPU-feature predicate from
//! `crate::cpu`, which is false off x86-64, so verified code never reaches
//! them there."""
    emu = "\n".join(out) + "\n"
    i = emu.index("#![allow(unused_imports)]")
    emu = head + "\n" + emu[i:]
    emu = emu.replace("use core::arch::x86_64::*;", "use crate::emu::{__m128i, __m256i};")
    emu = emu.replace("[ core::arch::x86_64::", "[ crate::emu::")
    assert "core::arch" not in emu.split("verus! {", 1)[1]
    open(sys.argv[3], "w").write(emu)
