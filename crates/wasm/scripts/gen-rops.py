w('    match op {')
for o in ['Copy'] + PGEN: w(f'        OpCode::P_{o} => true,')
w('        _ => false,')
w('    }')
w('}')
w('')
w('pub fn has_pre_x(op: OpCode) -> (r: bool)')
w('    ensures r == has_pre(op),')
w('{')
w('    proof { reveal(has_pre); }')
w('    match op {')
for o in ['Copy'] + PGEN: w(f'        OpCode::P_{o} => true,')
w('        _ => false,')
w('    }')
w('}')
w('')
w('/// The operation without its pre-copy.')
w('#[verifier::opaque]')
w('pub open spec fn unpre(op: OpCode) -> OpCode {')
w('    match op {')
for o in ['Copy'] + PGEN: w(f'        OpCode::P_{o} => OpCode::{o},')
w('        _ => op,')
w('    }')
w('}')
w('')
w('pub fn unpre_x(op: OpCode) -> (r: OpCode)')
w('    ensures r == unpre(op),')
w('{')
w('    proof { reveal(unpre); }')
w('    match op {')
for o in ['Copy'] + PGEN: w(f'        OpCode::P_{o} => OpCode::{o},')
w('        _ => op,')
w('    }')
w('}')
