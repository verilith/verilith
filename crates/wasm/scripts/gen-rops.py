w('pub proof fn lemma_unpre(op: OpCode, imm: u64, d1: u32)')
w('    requires has_pre(op),')
w('    ensures')
w('        fam(unpre(op)) == fam(op),')
w('        spec_instr(unpre(op), imm, d1) == spec_instr(op, imm, d1),')
w('        !has_pre(unpre(op)),')
w('        !(fam(op) is Op || fam(op) is Skip || fam(op) is BrIf || fam(op) is BrIfZ || fam(op) is BrIfRR')
