w('    match op {')
for o in ops: w(f'        OpCode::{o} => Fam::{fam_of(o)},')
w('    }')
w('}')
w('')
w('pub fn fam_x(op: OpCode) -> (r: Fam)')
w('    ensures r == fam(op),')
w('{')
w('    match op {')
for o in ops: w(f'        OpCode::{o} => Fam::{fam_of(o)},')
w('    }')
w('}')
w('')
def spec_instr_of(o):
    if o.startswith('P_') or o.startswith('A_'): return spec_instr_of(o[2:])
    if '_' not in o: return None
    pre, name = o.split('_', 1)
    if pre == 'Load': return f'{instr(name)}(imm as u32)'
    if pre in ('StoreRR','StoreRI'): return f'{instr(name)}(d1)'
    return instr(name)
