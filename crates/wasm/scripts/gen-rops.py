#!/usr/bin/env python3
"""Generates the specialized register operations: the `OpCode` enum and
`lower_bin`/`lower_un`/... in src/reg_ops.rs, and the dispatch arms in
src/run.rs (between the GENERATED ARMS markers). Run from the repository root."""

FB = {'F32Add','F32Sub','F32Mul','F32Div','F32Min','F32Max','F32Copysign',
      'F64Add','F64Sub','F64Mul','F64Div','F64Min','F64Max','F64Copysign'}
FC = {'F32Eq','F32Ne','F32Lt','F32Gt','F32Le','F32Ge','F64Eq','F64Ne','F64Lt','F64Gt','F64Le','F64Ge'}
FU = {'F32Abs','F32Neg','F32Sqrt','F64Abs','F64Neg','F64Sqrt'}

def instr(o):
    if o in FB: return f'Instr::FBin(FBinOp::{o})'
    if o in FC: return f'Instr::FCmp(FCmpOp::{o})'
    if o in FU: return f'Instr::FUn(FUnOp::{o})'
    return f'Instr::{o}'

CMP = ['I32Eq','I32Ne','I32LtS','I32LtU','I32GtS','I32GtU','I32LeS','I32LeU','I32GeS','I32GeU',
       'I64Eq','I64Ne','I64LtS','I64LtU','I64GtS','I64GtU','I64LeS','I64LeU','I64GeS','I64GeU']
BIN = CMP + ['I32Add','I32Sub','I32Mul','I32And','I32Or','I32Xor','I32Shl','I32ShrS','I32ShrU','I32Rotl','I32Rotr',
       'I64Add','I64Sub','I64Mul','I64And','I64Or','I64Xor','I64Shl','I64ShrS','I64ShrU','I64Rotl','I64Rotr',
       'F32Add','F32Sub','F32Mul','F32Div','F64Add','F64Sub','F64Mul','F64Div']
UN = ['I32Eqz','I64Eqz','I32Clz','I32Ctz','I32WrapI64','I64ExtendI32S','I64ExtendI32U',
      'I32Extend8S','I32Extend16S','F64Neg','F64Abs','F64Sqrt']
LOAD = ['I32Load','I64Load','F32Load','F64Load','I32Load8S','I32Load8U','I32Load16S','I32Load16U',
        'I64Load8U','I64Load32U']
STORE = ['I32Store','I64Store','F32Store','F64Store','I32Store8','I32Store16','I64Store8','I64Store32']
BRCMP = CMP

ops = ['Op','Skip','Copy','Const','Sel','BrIf','BrIfZ','Br',
       'UnG','BinRRG','BinRIG','LoadG','StoreRRG','StoreRIG','BrIfRRG','BrIfRIG']
ops += [f'Un_{o}' for o in UN]
ops += [f'BinRR_{o}' for o in BIN] + [f'BinRI_{o}' for o in BIN]
ops += [f'Load_{o}' for o in LOAD]
ops += [f'StoreRR_{o}' for o in STORE] + [f'StoreRI_{o}' for o in STORE]
ops += [f'BrIfRR_{o}' for o in BRCMP] + [f'BrIfRI_{o}' for o in BRCMP]

# Operations that can also start with a `local.get` (a pre-copy from slot
# `pa` to slot `pd`): the `P_` codes.
PI = [o for o in BIN if o.startswith('I32')] + ['I64Add','I64Sub','I64Mul','I64And','I64Or','I64Xor',
      'I64Shl','I64ShrS','I64ShrU','I64Eq','I64Ne','I64LtS','I64LtU','I64GtS','I64GtU',
      'F64Add','F64Sub','F64Mul','F64Div']
PGEN = ([f'Un_{o}' for o in ['I32Eqz','I64Eqz','I32WrapI64','I64ExtendI32S','I64ExtendI32U']]
        + [f'BinRR_{o}' for o in PI] + [f'BinRI_{o}' for o in PI]
        + [f'Load_{o}' for o in LOAD] + [f'StoreRR_{o}' for o in STORE] + [f'StoreRI_{o}' for o in STORE])
ops += ['P_Copy'] + ['P_' + o for o in PGEN]
# Operations that can read their first operand (slot `a`) from the
# accumulator, the previous operation's result: the `A_` codes.
# Only the common 32-bit operations get one: each code is another case of
# the dispatch, and the proof of the loop has to fit in one solver query.
AI32 = ['I32Add','I32Sub','I32Mul','I32And','I32Or','I32Xor','I32Shl','I32ShrS','I32ShrU','I32Rotl','I32Rotr']
ABRRR = ['I32Eq','I32Ne','I32LtS','I32LtU','I32GeS','I32GeU']
ABRRI = ['I32Eq','I32Ne','I32LtS','I32LtU']
AGEN = ([f'BinRI_{o}' for o in AI32 + ['I64Add']]
        + [f'BinRR_{o}' for o in ['I32Add','I32Sub','I32Mul','I32And','I32Or','I32Xor']]
        + [f'Load_{o}' for o in ['I32Load','I32Load8U','I64Load','F64Load']]
        + ['StoreRR_I32Store', 'StoreRR_F64Store', 'StoreRI_I32Store', 'StoreRI_I32Store8']
        + [f'BrIfRR_{o}' for o in ABRRR] + [f'BrIfRI_{o}' for o in ABRRI])
AHAND = ['BrIf', 'BrIfZ']
ops += ['A_' + o for o in AHAND + AGEN]
