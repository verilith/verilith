FAMS = ['Op','Skip','Copy','Const','Sel','Un','BinRR','BinRI','Load','StoreRR','StoreRI','BrIf','BrIfZ','BrIfRR','BrIfRI','Br']
def fam_of(o):
    if o in ('Op','Skip','Copy','Const','Sel','BrIf','BrIfZ','Br'): return o
    if o.startswith('P_') or o.startswith('A_'): return fam_of(o[2:])
    pre = o.split('_')[0]
    return {'UnG':'Un','BinRRG':'BinRR','BinRIG':'BinRI','LoadG':'Load','StoreRRG':'StoreRR','StoreRIG':'StoreRI',
            'BrIfRRG':'BrIfRR','BrIfRIG':'BrIfRI'}.get(o, pre)
w('/// The kind of a register operation.')
w('#[derive(Clone, Copy, PartialEq, Eq, Debug)]')
