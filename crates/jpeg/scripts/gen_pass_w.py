#!/usr/bin/env python3
"""Prints `pass_w` and `lemma_pass_link` of src/idct.rs: one pass of the
inverse DCT in wrapping 32-bit arithmetic, with the bookkeeping its proof
needs. Beside each machine value `vN` the proof keeps the exact value `gvN`
and the number `evN` of times 2^32 separates them. The text between the
`// BEGIN generated` and `// END generated` lines of src/idct.rs is this
script's output."""
lines, defs = [], []
cnt = [0]


def emit(kind, a, b=None, c=None):
    cnt[0] += 1
    v = "v%d" % cnt[0]
    ax, aT, ae = a
    T, e = "g" + v, "e" + v
    if kind == "mul":
        lines.append("    let %s = wmul(%s, %d);" % (v, ax, c))
        lines.append("    let ghost %s: int = %s * (%d);" % (T, aT, c))
        lines.append("    let ghost %s: int = %s * (%d) - wq(%s * (%d));" % (e, ae, c, ax, c))
        defs.append("%s == %s * (%d)" % (T, aT, c))
    else:
        bx, bT, be = b
        op = "+" if kind == "add" else "-"
        fn = "wadd" if kind == "add" else "wsub"
        lines.append("    let %s = %s(%s, %s);" % (v, fn, ax, bx))
        lines.append("    let ghost %s: int = %s %s %s;" % (T, aT, op, bT))
        lines.append("    let ghost %s: int = %s %s %s - wq(%s %s %s);" % (e, ae, op, be, ax, op, bx))
        defs.append("%s == %s %s %s" % (T, aT, op, bT))
    lines.append("    assert(%s == %s + 0x1_0000_0000 * %s);" % (v, T, e))
    return (v, T, e)


add = lambda a, b: emit("add", a, b)
sub = lambda a, b: emit("sub", a, b)
mul = lambda a, c: emit("mul", a, c=c)
x = [("x%d" % i, "x%d" % i, "0int") for i in range(8)]
xe = [("x%d" % i, "(x%d as int)" % i, "0int") for i in range(8)]


def build(x):
    z1 = mul(add(x[2], x[6]), 4433)
    t2 = add(z1, mul(x[6], -15137))
    t3 = add(z1, mul(x[2], 6270))
    t0 = mul(add(x[0], x[4]), 8192)
    t1 = mul(sub(x[0], x[4]), 8192)
    t10, t13, t11, t12 = add(t0, t3), sub(t0, t3), add(t1, t2), sub(t1, t2)
    z1, z2, z3, z4 = add(x[7], x[1]), add(x[5], x[3]), add(x[7], x[3]), add(x[5], x[1])
    z5 = mul(add(z3, z4), 9633)
    z1, z2 = mul(z1, -7373), mul(z2, -20995)
    z3, z4 = add(mul(z3, -16069), z5), add(mul(z4, -3196), z5)
    u0 = add(add(mul(x[7], 2446), z1), z3)
    u1 = add(add(mul(x[5], 16819), z2), z4)
    u2 = add(add(mul(x[3], 25172), z2), z3)
    u3 = add(add(mul(x[1], 12299), z1), z4)
    return [add(t10, u3), add(t11, u2), add(t12, u1), add(t13, u0), sub(t13, u0), sub(t12, u1), sub(t11, u2), sub(t10, u3)]


# The lemma's hypotheses: the same definitions over plain integers.
build(x)
ldefs, n = list(defs), cnt[0]
lines.clear(); defs.clear(); cnt[0] = 0
outs = build(xe)
xs = ["x%d" % i for i in range(8)]
gs = ["gv%d" % i for i in range(1, n + 1)]
seq_i = "seq![%s]" % ", ".join(xs)
seq_e = "seq![%s]" % ", ".join("%s as int" % v for v in xs)
print("// BEGIN generated by scripts/gen_pass_w.py")
print("/// The exact values of a pass, named one by one, are `idct_1d`'s.")
print("pub proof fn lemma_pass_link(%s)" % ", ".join("%s: int" % v for v in xs + gs))
print("    requires")
for d in ldefs:
    print("        %s," % d)
print("    ensures")
for i, o in enumerate(outs):
    print("        idct_1d(%s)[%d] == %s," % (seq_i, i, o[1]))
print("{\n}\n")
print("/// One pass in wrapping 32-bit arithmetic: right modulo 2^32.")
print("#[inline(always)]")
print("fn pass_w(%s) -> (r: (i32, i32, i32, i32, i32, i32, i32, i32))" % ", ".join("%s: i32" % v for v in xs))
print("    ensures")
for i in range(8):
    print("        cong(r.%d as int, idct_1d(%s)[%d])," % (i, seq_e, i))
print("{")
print("    hide(idct_1d);")
print("    hide(cong);")
print("\n".join(lines))
print("    proof {")
print("        lemma_pass_link(%s);" % ", ".join(["%s as int" % v for v in xs] + gs))
for i, o in enumerate(outs):
    print("        lemma_cong_k(%s as int, %s, %s);" % o)
print("    }")
print("    (%s)" % ", ".join(o[0] for o in outs))
print("}")
print("// END generated")
