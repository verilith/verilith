#!/usr/bin/env python3
"""Writes src/pow5.rs: 5^q for q in -342..=308 as 128-bit truncated,
normalized significands (the table of the Eisel-Lemire algorithm, generated
as in fast_float's script)."""
rows = []
for q in range(-342, 0):
    p = 5 ** -q
    z = 0
    while (1 << z) < p:
        z += 1
    if q >= -27:
        c = 2 ** (z + 127) // p + 1
    else:
        c = 2 ** (2 * z + 128) // p + 1
        while c >= (1 << 128):
            c //= 2
    rows.append(c)
for q in range(0, 309):
    p = 5 ** q
    while p < (1 << 127):
        p *= 2
    while p >= (1 << 128):
        p //= 2
    rows.append(p)
def rows4(xs):
    return ",\n".join("    " + ", ".join("0x%016x" % x for x in xs[i:i + 4]) for i in range(0, len(xs), 4))
hi = [c >> 64 for c in rows]
lo = [c & ((1 << 64) - 1) for c in rows]
out = """// Generated by scripts/gen_pow5.py. Do not edit.
use vstd::prelude::*;

verus! {

/// High halves of 5^q as 128-bit normalized significands, for
/// q = -342..=308 (the Eisel-Lemire table, as in fast_float). What each
/// entry is, is checked by evaluation in `float.rs`.
pub const POW5_HI: [u64; %d] = [
%s,
];

/// Low halves, as `POW5_HI`.
pub const POW5_LO: [u64; %d] = [
%s,
];

} // verus!
""" % (len(rows), rows4(hi), len(rows), rows4(lo))
open("src/pow5.rs", "w").write(out)
