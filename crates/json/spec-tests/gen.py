"""Writes src/cases.rs: one proof function per JSONTestSuite file, asserting
what spec::document(bytes, true) must be, proved by evaluation.

  y_ files must be accepted, n_ files rejected. i_ files are the ones where
  RFC 8259 leaves the choice to the parser; the expectations below are the
  choices README.md documents ("How verilith-json reads RFC 8259"), written
  here from that table, not from what the code does.
"""
import os, re, sys

suite, out = sys.argv[1], sys.argv[2]

# Left out: nesting 500 levels deep or more goes past the recursion depth of
# Verus's evaluator (which stops with an error, not a wrong answer). The
# Rust tests run these three on the parser, which is proven equal to the
# spec.
LEFT_OUT = {
    "i_structure_500_nested_arrays.json",
    "n_structure_100000_opening_arrays.json",
    "n_structure_open_array_object.json",
}

def expect(name):
    if name.startswith("y_"):
        return True
    if name.startswith("n_"):
        return False
    # i_: numbers beyond f64 range are accepted; 500 levels of nesting is
    # under the limit of 1000; a BOM is skipped; text that is not UTF-8 (lone
    # surrogate escapes included, since they cannot be decoded to UTF-8) is
    # rejected.
    if name.startswith(("i_number_", "i_structure_")):
        return True
    if name.startswith(("i_string_", "i_object_key_")):
        return False
    raise SystemExit(f"gen.py: no expectation for {name}")

lines = [
    "// @generated by gen.py from JSONTestSuite. Do not edit.",
    "use verilith_json::spec::document;",
    "use vstd::prelude::*;",
    "",
    "verus! {",
    "",
]
n = 0
skipped = []
for name in sorted(os.listdir(suite)):
    if not name.endswith(".json"):
        continue
    data = open(os.path.join(suite, name), "rb").read()
    if name in LEFT_OUT:
        skipped.append(name)
        continue
    n += 1
    fn = "c%03d_%s" % (n, re.sub(r"[^A-Za-z0-9]", "_", name[:-5]).lower())
    s = "seq![" + ", ".join("%du8" % b for b in data) + "]" if data else "Seq::<u8>::empty()"
    want = "is Some" if expect(name) else "is None"
    lines.append(f"// {name}")
    lines.append(f"proof fn {fn}() {{")
    lines.append(f"    assert(document({s}, true) {want}) by (compute_only);")
    lines.append("}")
    lines.append("")
lines.append("} // verus!")
open(os.path.join(out, "cases.rs"), "w").write("\n".join(lines) + "\n")
open(os.path.join(out, "cases.count"), "w").write(f"{n}\n")
if len(skipped) != len(LEFT_OUT):
    raise SystemExit(f"gen.py: expected to leave out {sorted(LEFT_OUT)}, left out {skipped}")
print(f"{n} cases, left out: {' '.join(skipped)}")
