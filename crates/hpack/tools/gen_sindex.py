#!/usr/bin/env python3
"""Generates src/sindex.rs from src/stable.rs: a perfect hash of the static
table's names, for the encoder's lookups.

    tools/gen_sindex.py src

The index is not trusted. The encoder compares every candidate it gives
with the static table entry itself (`encoder::find_static`), so a wrong
index can only make the encoder miss a match, never use a wrong one.
"""
import re
import sys

d = sys.argv[1]
ents = re.findall(r'\(b"([^"]*)", b"([^"]*)"\)', open(d + "/stable.rs").read())
assert len(ents) == 61
names = []
for n, _ in ents:
    if n not in names:
        names.append(n)
first = {n: next(i for i, (m, _) in enumerate(ents) if m == n) for n in names}
count = {n: sum(1 for m, _ in ents if m == n) for n in names}
for n in names:  # entries with one name are consecutive
    assert all(ents[first[n] + k][0] == n for k in range(count[n]))


def h(b, a, c):
    return (len(b) + a * b[1] + c * b[-1]) % 256


params = next((a, c) for a in range(64) for c in range(64)
              if len({h(n.encode(), a, c) for n in names}) == len(names))
at = [0] * 256
for n in names:
    at[h(n.encode(), *params)] = first[n] + 1
cnt = [0] * 62
for n in names:
    cnt[first[n] + 1] = count[n]


def rows(xs):
    return "\n".join("    " + " ".join(f"{x}," for x in xs[i:i + 16]) for i in range(0, len(xs), 16))


open(d + "/sindex.rs", "w").write(f"""// Generated by tools/gen_sindex.py from src/stable.rs. Do not edit.
//
// A perfect hash of the static table's names: `NAME_AT[sh(name)]` is the
// first index (1-based) of the entries with that name, or 0, and
// `NAME_CNT[i]` how many consecutive entries from `i` have it. Not
// trusted: every candidate is compared with the table itself.
use vstd::prelude::*;

verus! {{

pub const SH_A: usize = {params[0]};
pub const SH_C: usize = {params[1]};

pub const NAME_AT: [u8; 256] = [
{rows(at)}
];

pub const NAME_CNT: [u8; 62] = [
{rows(cnt)}
];

}} // verus!
""")
