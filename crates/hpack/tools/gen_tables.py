#!/usr/bin/env python3
"""Generates src/htables.rs and src/stable.rs: RFC 7541's Huffman code (Appendix B) and static
table (Appendix A).

Reads them from two independent implementations and fails unless they
agree entry for entry: nghttp2 (lib/nghttp2_hd_huffman_data.c,
lib/nghttp2_hd.c) and Go's golang.org/x/net/http2/hpack (tables.go,
gen.go). tests/tables.rs then checks the generated code is prefix-free and
canonical, and the static table against the RFC's text as quoted there.

    tools/gen_tables.py NGHTTP2_DIR GO_NET_DIR src
"""
import re
import sys


def nghttp2(d):
    src = open(d + "/lib/nghttp2_hd_huffman_data.c").read()
    body = src[src.index("huff_sym_table[] = {"):]
    body = body[:body.index("};")]
    pairs = re.findall(r"\{(\d+),\s*0x([0-9A-Fa-f]+)U\}", body)
    huff = [(int(c, 16) >> (32 - int(n)), int(n)) for n, c in pairs]
    hd = open(d + "/lib/nghttp2_hd.c").read()
    st = re.findall(r'MAKE_STATIC_ENT\("([^"]*)", "([^"]*)",', hd)
    return huff, st


def gonet(d):
    t = open(d + "/http2/hpack/tables.go").read()
    codes = t[t.index("var huffmanCodes = [256]uint32{"):]
    codes = [int(x, 16) for x in re.findall(r"0x([0-9a-f]+),", codes[:codes.index("}")])]
    lens = t[t.index("var huffmanCodeLen = [256]uint8{"):]
    lens = [int(x) for x in re.findall(r"(\d+),", lens[:lens.index("}")])]
    g = open(d + "/http2/hpack/gen.go").read()
    g = g[g.index("var staticTableEntries"):]
    st = [(n, v or "") for n, v in
          re.findall(r'\{Name: "([^"]*)"(?:, Value: "([^"]*)")?\}', g[:g.index("\n}\n")])]
    return list(zip(codes, lens)), st


def main():
    h1, s1 = nghttp2(sys.argv[1])
    h2, s2 = gonet(sys.argv[2])
    assert len(h1) == 257 and len(h2) == 256, (len(h1), len(h2))
    assert h1[:256] == h2, "Huffman tables disagree"
    assert h1[256] == ((1 << 30) - 1, 30), "EOS"
    assert len(s1) == 61 and s1 == s2, "static tables disagree"
    out = sys.argv[3]
    lens = [n for _, n in h1]
    # The canonical layout that src/huffman.rs checks at run time: for each
    # length l, the symbols of that length in order (SYMS from OFF[l]),
    # whose codes are FIRST[l], FIRST[l] + 1, ... (the check fails if the
    # code is not canonical, and the decoder refuses to start).
    cnt = [0] * 31
    for n in lens:
        cnt[n] += 1
    first = [0] * 31
    code = 0
    for l in range(1, 31):
        code = (code + cnt[l - 1]) << 1 if l > 1 else 0
        first[l] = code
    off = [0] * 31
    for l in range(1, 31):
        off[l] = off[l - 1] + cnt[l - 1] if l > 1 else 0
    syms = sorted(range(257), key=lambda s: (lens[s], s))
    with open(out + "/htables.rs", "w") as f:
        w = f.write
        w("// Generated by tools/gen_tables.py from nghttp2 and golang.org/x/net/http2/hpack,\n")
        w("// which agree entry for entry. Do not edit.\n")
        w("use vstd::prelude::*;\n\nverus! {\n\n")
        w("/// RFC 7541 Appendix B: the code of each symbol (256 is EOS), first bit\n")
        w("/// most significant ...\n")
        w("pub const HUFF_CODE: [u32; 257] = [\n")
        for i in range(0, 257, 8):
            w("    " + " ".join("0x%x," % h1[j][0] for j in range(i, min(i + 8, 257))) + "\n")
        w("];\n\n/// ... and its length in bits.\npub const HUFF_LEN: [u8; 257] = [\n")
        for i in range(0, 257, 16):
            w("    " + " ".join("%d," % lens[j] for j in range(i, min(i + 16, 257))) + "\n")
        w("];\n\n// The canonical layout (not trusted: checked by huffman::check).\n")
        w("pub const FIRST: [u32; 31] = [%s];\n" % ", ".join(map(str, first)))
        w("pub const CNT: [u32; 31] = [%s];\n" % ", ".join(map(str, cnt)))
        w("pub const OFF: [u32; 31] = [%s];\n" % ", ".join(map(str, off)))
        w("pub const SYMS: [u16; 257] = [\n")
        for i in range(0, 257, 16):
            w("    " + " ".join("%d," % syms[j] for j in range(i, min(i + 16, 257))) + "\n")
        w("];\n\n} // verus!\n")
    with open(out + "/stable.rs", "w") as f:
        w = f.write
        w("// Generated by tools/gen_tables.py from nghttp2 and golang.org/x/net/http2/hpack,\n")
        w("// which agree entry for entry. Do not edit.\n")
        w("//\n// RFC 7541 Appendix A: the static table, entries 1 to 61.\n")
        w("pub const STATIC: [(&[u8], &[u8]); 61] = [\n")
        for n, v in s1:
            w('    (b"%s", b"%s"),\n' % (n, v))
        w("];\n")


main()
