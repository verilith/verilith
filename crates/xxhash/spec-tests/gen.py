"""Writes src/cases.rs from xxHash's tests/sanity_test_vectors.h: for each
XXH32 and XXH64 entry with seed 0 and a length up to MAX_LEN, a proof
function asserting that the spec's hash of the test buffer is the value
xxHash gives, proved by evaluation.

The buffer is xxHash's own (fillTestBuffer in tests/sanity_test.c): byte i
is the top byte of PRIME32 * PRIME64^i modulo 2^64. The spec has no seed
parameter (verilith-xxhash hashes with seed 0, as LZ4 and zstd do), so the
entries with other seeds are left out.
"""
import re, sys

header, out = sys.argv[1], sys.argv[2]
MAX_LEN = 256   # every stripe count and tail length, many times over

PRIME32 = 2654435761
PRIME64 = 11400714785074694797
def buffer(n):
    b, g = [], PRIME32
    for _ in range(n):
        b.append(g >> 56)
        g = (g * PRIME64) % 2**64
    return b

def entries(name):
    text = open(header).read()
    body = text.split(f"XSUM_{name}_testdata[] = {{", 1)[1].split("};", 1)[0]
    return [(int(a), int(s, 16), int(r, 16)) for a, s, r in
            re.findall(r"\{\s*(\d+),\s*0x([0-9A-Fa-f]+)U(?:LL)?,\s*0x([0-9A-Fa-f]+)U(?:LL)?\s*\}", body)]

def seq(b):
    return "seq![" + ", ".join("%du8" % x for x in b) + "]" if b else "Seq::<u8>::empty()"

lines = [
    "// @generated by gen.py from xxHash's sanity test vectors. Do not edit.",
    "use verilith_xxhash::spec::*;",
    "use vstd::prelude::*;",
    "",
    "verus! {",
    "",
]
n = 0
for name, fn, ty, reveals in [
    ("XXH32", "xxh32", "u32", ["add32", "mul32", "rotl32", "round32"]),
    ("XXH64", "xxh64", "u64", ["add64", "mul64", "rotl64", "round64", "merge64"]),
]:
    es = [(l, r) for l, s, r in entries(name) if s == 0 and l <= MAX_LEN]
    assert len(es) == MAX_LEN + 1, (name, len(es))
    for l, r in es:
        n += 1
        lines.append(f"// XSUM_{name}_testdata, len {l}, seed 0")
        lines.append(f"proof fn c{n:03d}_{fn}_{l}() {{")
        # The word operations are opaque to the proofs; revealing them lets
        # the evaluator run them.
        lines.append("    " + " ".join(f"reveal({r_});" for r_ in reveals))
        lines.append(f"    assert({fn}({seq(buffer(l))}) == {r:#x}{ty}) by (compute_only);")
        lines.append("}")
        lines.append("")
lines.append("} // verus!")
open(f"{out}/cases.rs", "w").write("\n".join(lines) + "\n")
open(f"{out}/cases.count", "w").write(f"{n}\n")
print(f"{n} cases")
