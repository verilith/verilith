#!/usr/bin/env python3
"""Writes src/base64/tables.rs: the encode and decode tables for both
alphabets. Each table is proven equal to its spec function (`sym`, `val`)
in that file, so this script is not trusted."""
STD = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
URL = STD[:62] + "-_"

def dec(a):
    t = [0xFF] * 256
    for i, c in enumerate(a):
        t[ord(c)] = i
    return t

def rows(t, w=16):
    return "\n".join("    " + ", ".join(str(x) for x in t[i:i + w]) + "," for i in range(0, len(t), w))

def table(name, t, doc):
    return f"/// {doc}\npub const {name}: [u8; {len(t)}] = [\n{rows(t)}\n];\n"

out = ["// Generated by tools/gen_b64.py. Do not edit.",
       "use super::spec::*;",
       "use vstd::compute::RangeAll;",
       "use vstd::prelude::*;",
       "",
       "verus! {",
       "",
       table("ENC_STD", [ord(c) for c in STD], "`sym(false, v)` for each value."),
       table("ENC_URL", [ord(c) for c in URL], "`sym(true, v)` for each value."),
       table("DEC_STD", dec(STD), "`val(false, c)`, with 255 for `None`."),
       table("DEC_URL", dec(URL), "`val(true, c)`, with 255 for `None`."),
       """/// The value a decode table holds for `c`.
pub open spec fn dec_entry(url: bool, c: u8) -> u8 {
    match val(url, c) {
        Some(x) => x,
        None => 255,
    }
}

pub proof fn lemma_tables()
    ensures
        forall|x: u8| x < 64 ==> #[trigger] ENC_STD@[x as int] == sym(false, x),
        forall|x: u8| x < 64 ==> #[trigger] ENC_URL@[x as int] == sym(true, x),
        forall|c: u8| #[trigger] DEC_STD@[c as int] == dec_entry(false, c),
        forall|c: u8| #[trigger] DEC_URL@[c as int] == dec_entry(true, c),
{
    let p0 = |i: int| ENC_STD@[i] == sym(false, i as u8);
    assert((0..64int).all_spec(|i: int| ENC_STD@[i] == sym(false, i as u8))) by (compute_only);
    vstd::compute::all_spec_ensures(0..64int, p0);
    let p1 = |i: int| ENC_URL@[i] == sym(true, i as u8);
    assert((0..64int).all_spec(|i: int| ENC_URL@[i] == sym(true, i as u8))) by (compute_only);
    vstd::compute::all_spec_ensures(0..64int, p1);
    let p2 = |i: int| DEC_STD@[i] == dec_entry(false, i as u8);
    assert((0..256int).all_spec(|i: int| DEC_STD@[i] == dec_entry(false, i as u8))) by (compute_only);
    vstd::compute::all_spec_ensures(0..256int, p2);
    let p3 = |i: int| DEC_URL@[i] == dec_entry(true, i as u8);
    assert((0..256int).all_spec(|i: int| DEC_URL@[i] == dec_entry(true, i as u8))) by (compute_only);
    vstd::compute::all_spec_ensures(0..256int, p3);
    assert forall|x: u8| x < 64 implies #[trigger] ENC_STD@[x as int] == sym(false, x) by {
        assert(p0(x as int));
    }
    assert forall|x: u8| x < 64 implies #[trigger] ENC_URL@[x as int] == sym(true, x) by {
        assert(p1(x as int));
    }
    assert forall|c: u8| #[trigger] DEC_STD@[c as int] == dec_entry(false, c) by {
        assert(p2(c as int));
    }
    assert forall|c: u8| #[trigger] DEC_URL@[c as int] == dec_entry(true, c) by {
        assert(p3(c as int));
    }
}

} // verus!
"""]
open("src/base64/tables.rs", "w").write("\n".join(out))
