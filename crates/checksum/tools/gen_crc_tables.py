P = 0xEDB88320
t0 = []
for n in range(256):
    c = n
    for _ in range(8):
        c = (c >> 1) ^ P if c & 1 else c >> 1
    t0.append(c)
T = [t0]
for k in range(1, 16):
    T.append([(T[-1][n] >> 8) ^ t0[T[-1][n] & 0xFF] for n in range(256)])

