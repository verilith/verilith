#!/usr/bin/env python3
"""Writes src/tables.rs from RE2's Unicode tables.

Usage: tools/gen_tables.py RE2_DIR > src/tables.rs

RE2_DIR is an RE2 checkout. The general category and script ranges come
from re2/unicode_groups.cc and the case folding orbits from
re2/unicode_casefold.cc, so that vregex's classes are RE2's, code point for
code point. scripts/check_tables.sh checks that src/tables.rs is what this
script prints.

Layout:
  GROUP_NAMES/GROUP_NAME_OFF  the names, concatenated, and where each starts
  GROUP_OFF                   where each group's ranges start
  GROUP_LO/GROUP_HI           the ranges, sorted and not touching, per group
  FOLD_A/FOLD_B               every ordered pair (a, b), a != b, of code
                              points with the same simple case folding,
                              sorted by a then b
"""
import re
import sys

EVEN_ODD, ODD_EVEN = 1, -1
EVEN_ODD_SKIP = 1 << 30
ODD_EVEN_SKIP = EVEN_ODD_SKIP + 1


def groups(src):
    arrays = {}
    for m in re.finditer(r"static const URange(16|32) (\w+)\[\] = \{(.*?)\};", src, re.S):
        arrays[m.group(2)] = [(int(a, 0), int(b, 0)) for a, b in re.findall(r"\{\s*(\w+),\s*(\w+)\s*\}", m.group(3))]
    out = []
    table = src[src.index("const UGroup unicode_groups[]"):]
    for m in re.finditer(r'\{ "(\w+)", \+1, (\w+), (\d+), (\w+), (\d+) \}', table):
        name, r16, n16, r32, n32 = m.groups()
        rs = []
        if r16 != "0":
            assert len(arrays[r16]) == int(n16)
            rs += arrays[r16]
        if r32 != "0":
            assert len(arrays[r32]) == int(n32)
            rs += arrays[r32]
        rs.sort()
        merged = []
        for lo, hi in rs:
            assert lo <= hi <= 0x10FFFF
            if merged and lo <= merged[-1][1] + 1:
                assert lo == merged[-1][1] + 1
                merged[-1] = (merged[-1][0], hi)
            else:
                merged.append((lo, hi))
        out.append((name, merged))
    n = int(re.search(r"num_unicode_groups = (\d+)", src).group(1))
    assert len(out) == n, (len(out), n)
    assert [g[0] for g in out] == sorted(g[0] for g in out)
    return out


def folds(src):
    body = src[src.index("const CaseFold unicode_casefold[]"):src.index("const int num_unicode_casefold")]
    env = {"EvenOdd": EVEN_ODD, "OddEven": ODD_EVEN, "EvenOddSkip": EVEN_ODD_SKIP, "OddEvenSkip": ODD_EVEN_SKIP}
    nxt = {}
    for lo, hi, d in re.findall(r"\{\s*(\d+),\s*(\d+),\s*([-\w]+)\s*\}", body):
        lo, hi = int(lo), int(hi)
        d = env[d] if d in env else int(d)
        for r in range(lo, hi + 1):
            if d in (EVEN_ODD_SKIP, ODD_EVEN_SKIP) and (r - lo) % 2:
                continue
            if d in (EVEN_ODD, EVEN_ODD_SKIP):
                t = r + 1 if r % 2 == 0 else r - 1
            elif d in (ODD_EVEN, ODD_EVEN_SKIP):
                t = r + 1 if r % 2 == 1 else r - 1
            else:
                t = r + d
            nxt[r] = t
    pairs = []
    for r in sorted(nxt):
        orbit = []
        t = nxt[r]
        while t != r:
            orbit.append(t)
            t = nxt[t]
            assert len(orbit) < 8
        for t in sorted(orbit):
            pairs.append((r, t))
    return pairs


def arr(name, ty, vals, per=12):
    lines = [f"pub static {name}: [{ty}; {len(vals)}] = ["]
    for i in range(0, len(vals), per):
        lines.append("    " + " ".join(f"{v}," for v in vals[i:i + per]))
    lines.append("];")
    return "\n".join(lines)


def main():
    d = sys.argv[1]
    gs = groups(open(f"{d}/re2/unicode_groups.cc").read())
    ps = folds(open(f"{d}/re2/unicode_casefold.cc").read())
    names = b"".join(g[0].encode() for g in gs)
    name_off, off, lo, hi = [0], [0], [], []
    for name, rs in gs:
        name_off.append(name_off[-1] + len(name))
        lo += [r[0] for r in rs]
        hi += [r[1] for r in rs]
        off.append(len(lo))
    print("// Generated by tools/gen_tables.py from RE2's Unicode tables (Unicode 15.1). Do not edit.")
    print("#![cfg_attr(rustfmt, rustfmt_skip)]")
    print(f"pub const NGROUPS: usize = {len(gs)};")
    print(arr("GROUP_NAMES", "u8", list(names), 24))
    print(arr("GROUP_NAME_OFF", "u32", name_off))
    print(arr("GROUP_OFF", "u32", off))
    print(arr("GROUP_LO", "u32", lo))
    print(arr("GROUP_HI", "u32", hi))
    print(arr("FOLD_A", "u32", [p[0] for p in ps]))
    print(arr("FOLD_B", "u32", [p[1] for p in ps]))


main()
