#!/usr/bin/env python3
"""buckify.py [--check]: writes the Buck2 files from the Cargo ones.

Cargo.toml and Cargo.lock are the one description of the crates. This turns
them into crates/<name>/BUCK for every crate with proofs
([package.metadata.verus] verify = true) and third-party/BUCK for what those
need from crates.io, so that Buck2 verifies each crate as `cargo verus focus`
does in its directory: default features, the same vstd features, the same
dependencies. (A crate whose scripts/verify.sh passes --features is verified
with those too; see verify-features below.)

    scripts/buckify.py           rewrite the files
    scripts/buckify.py --check   fail if a file is out of date, or a BUCK
                                 file exists for a crate that should not
                                 have one (CI runs this)

Two things a crate's Cargo.toml can say about how it is verified:

    [package.metadata.verilith]
    verify-parts = 4               # verify it as 4 parts (BUILDING.md)
    verify-features = ["cjson"]    # verify it with these features on top of
                                   # the default ones

Anything this script does not know how to reproduce exactly is an error, not
a guess. Standard library only; needs cargo.
"""
import json
import os
import re
import subprocess
import sys

try:
    import tomllib
except ImportError:  # Python < 3.11
    tomllib = None

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = ("# @" + "generated by scripts/buckify.py from Cargo.toml and Cargo.lock.\n"
          "# Do not edit: change the Cargo files and run scripts/buckify.py.\n")
# Supplied by the Verus build itself, never compiled here.
VERUS_BUILTIN = {"verus_builtin", "verus_builtin_macros", "verus_state_machines_macros"}
# crates.io dependencies with a build script, and why ignoring it is right.
# A dependency with a build script that is not listed here is an error.
REVIEWED_BUILD_SCRIPTS = {
    # 1.0.23: sets zmij_no_select_unpredictable for rustc < 1.88 and
    # opt_level="s" when optimizing for size. Neither applies.
    "zmij": {"1.0.23"},
}


def die(msg):
    sys.exit(f"buckify.py: {msg}")


def metadata():
    return json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))


def lock_checksums():
    out = {}
    text = open(os.path.join(ROOT, "Cargo.lock"), encoding="utf-8").read()
    for block in text.split("[[package]]")[1:]:
        f = dict(re.findall(r'^(\w+) = "([^"]*)"', block, re.M))
        if "checksum" in f:
            out[(f["name"], f["version"])] = f["checksum"]
    return out


def enabled(pkg, start):
    """The features of pkg that `start` turns on, the optional dependencies
    they enable, and the features they ask of each dependency."""
    table = pkg["features"]
    on, deps_on, dep_feats = set(), set(), {}
    todo = list(start)
    while todo:
        f = todo.pop()
        if f.startswith("dep:"):
            deps_on.add(f[4:])
        elif "/" in f:
            dep, feat = f.split("/", 1)
            if dep.endswith("?"):
                dep = dep[:-1]
            else:
                deps_on.add(dep)
            dep_feats.setdefault(dep, set()).add(feat)
        elif f not in on:
            if f not in table:
                die(f"{pkg['name']}: no feature {f!r}")
            on.add(f)
            todo += table[f]
    return on, deps_on, dep_feats


def verilith_meta(pkg):
    return (pkg.get("metadata") or {}).get("verilith") or {}


def verify_features(pkg):
    """The features a crate is verified with: its defaults, plus any it names
    in [package.metadata.verilith] verify-features. The crate's own
    scripts/verify.sh (the cargo verus way) must ask for the same ones."""
    extra = list(verilith_meta(pkg).get("verify-features", []))
    script = os.path.join(os.path.dirname(pkg["manifest_path"]), "scripts", "verify.sh")
    in_script = []
    if os.path.exists(script):
        text = open(script, encoding="utf-8").read()
        if "--no-default-features" in text or "--all-features" in text:
            die(f"{script}: buckify.py has not been taught --no-default-features or --all-features")
        for m in re.finditer(r"--features[ =]+(\"[^\"]*\"|'[^']*'|\S+)", text):
            in_script += re.split(r"[ ,]+", m.group(1).strip("\"'"))
    if sorted(set(in_script)) != sorted(set(extra)):
        die(f"{pkg['name']}: scripts/verify.sh verifies with features {sorted(set(in_script))} but "
            f"[package.metadata.verilith] verify-features is {sorted(set(extra))}")
    return enabled(pkg, (["default"] if "default" in pkg["features"] else []) + extra)


def default_features(pkg):
    return enabled(pkg, ["default"] if "default" in pkg["features"] else [])


def dep_request(pkg, dep_decl, dep_pkg, extra):
    """The features of dep_pkg that pkg (with its default features) turns on."""
    start = set(dep_decl["features"]) | extra
    if dep_decl["uses_default_features"] and "default" in dep_pkg["features"]:
        start.add("default")
    return enabled(dep_pkg, sorted(start))[0]


def crate_dir(pkg):
    return os.path.relpath(os.path.dirname(pkg["manifest_path"]), ROOT)


def lib_target(pkg):
    libs = [t for t in pkg["targets"] if set(t["kind"]) & {"lib", "rlib", "staticlib", "cdylib"}]
    if len(libs) != 1:
        die(f"{pkg['name']}: expected one library target")
    return libs[0]


def outside_includes(pkg_dir, src_dir):
    """Files outside src/ that the sources include (include_str!("../README.md"))."""
    found = set()
    for base, _, files in os.walk(os.path.join(ROOT, src_dir)):
        for f in files:
            if not f.endswith(".rs"):
                continue
            path = os.path.join(base, f)
            for m in re.finditer(r'\binclude(?:_str|_bytes)?!\(\s*"([^"]+)"',
                                 open(path, encoding="utf-8").read()):
                target = os.path.normpath(os.path.join(base, m.group(1)))
                rel = os.path.relpath(target, os.path.join(ROOT, pkg_dir))
                if rel.startswith(".."):
                    die(f"{path}: includes a file outside the crate")
                if not rel.startswith("src" + os.sep):
                    found.add(rel)
    return sorted(found)


def fmt_list(items, indent="    "):
    if not items:
        return "[]"
    if len(items) == 1:
        return f'["{items[0]}"]'
    return "[\n" + "".join(f'{indent}    "{i}",\n' for i in items) + indent + "]"


def generate():
    meta = metadata()
    by_id = {p["id"]: p for p in meta["packages"]}
    members = [by_id[i] for i in meta["workspace_members"]]
    by_name = {}
    for p in meta["packages"]:
        by_name.setdefault(p["name"], []).append(p)
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    checksums = lock_checksums()

    def resolve_dep(pkg, decl):
        """The package a dependency declaration of pkg resolves to."""
        for d in nodes[pkg["id"]]["deps"]:
            cand = by_id[d["pkg"]]
            if cand["name"] == decl["name"]:
                return cand
        return None

    verified = {p["name"]: p for p in members
                if ((p.get("metadata") or {}).get("verus") or {}).get("verify")}
    files = {}
    vstd_variants = {}   # frozenset(features) -> target name
    third_party = {}     # name -> (pkg, features)
    info = {}            # package name -> dict

    for name, pkg in sorted(verified.items()):
        d = crate_dir(pkg)
        parts = d.split(os.sep)
        if len(parts) != 2 or parts[0] != "crates":
            die(f"{name}: a verified crate outside crates/")
        on, deps_on, dep_feats = verify_features(pkg)
        lib = lib_target(pkg)
        src_root = os.path.relpath(lib["src_path"], os.path.join(ROOT, d))
        if src_root != os.path.join("src", "lib.rs"):
            die(f"{name}: crate root is {src_root}, expected src/lib.rs")
        if os.path.exists(os.path.join(ROOT, d, "build.rs")):
            # A build script may set cfgs. The ones here only do so for tests.
            text = open(os.path.join(ROOT, d, "build.rs"), encoding="utf-8").read()
            cfgs = set(re.findall(r"rustc-cfg=(\w+)", text))
            if cfgs - {"have_cares"} or "rustc-env" in text or "OUT_DIR" in text:
                die(f"{name}: build.rs does something buckify.py has not been taught")
        vstd_feats, deps, externs = None, [], []
        for decl in pkg["dependencies"]:
            if decl["kind"] is not None:
                continue  # dev and build dependencies play no part in the proofs
            if decl["optional"] and decl["name"] not in deps_on:
                continue
            if decl.get("target"):
                die(f"{name}: target-specific dependency {decl['name']}")
            dep = resolve_dep(pkg, decl)
            if dep is None:
                die(f"{name}: cannot resolve dependency {decl['name']}")
            if decl.get("rename"):
                die(f"{name}: renamed dependency {decl['name']}")
            want = dep_request(pkg, decl, dep, dep_feats.get(decl["name"], set()))
            if dep["name"] == "vstd":
                vstd_feats = want
            elif dep["name"] in VERUS_BUILTIN:
                continue
            elif dep["name"] in verified:
                deps.append((dep["name"], want))
            elif dep["source"] and dep["source"].startswith("registry+"):
                externs.append((dep, want))
            else:
                die(f"{name}: depends on {dep['name']}, which is neither verified nor from crates.io")
        if vstd_feats is None:
            die(f"{name}: verified crates must depend on vstd")
        info[name] = {
            "pkg": pkg, "dir": d, "short": parts[1], "features": on, "vstd": vstd_feats,
            "deps": deps, "externs": externs, "crate": lib["name"].replace("-", "_"),
            "defaults": default_features(pkg)[0],
            "parts": int(verilith_meta(pkg).get("verify-parts", 1)),
        }

    # Cargo builds one vstd, and one copy of each dependency, for the crate
    # being verified. Buck2 compiles each crate once, with its own default
    # features. Those agree only if every crate asks of its dependencies what
    # they have by default, and the same vstd.
    def closure(name, seen=None):
        seen = seen if seen is not None else {}
        for dep, want in info[name]["deps"]:
            seen.setdefault(dep, set()).update(want)
            closure(dep, seen)
        return seen

    for name, i in sorted(info.items()):
        vstd = set(i["vstd"])
        for dep, want in closure(name).items():
            have = info[dep]["features"]  # what Buck2 compiles dep with
            if want - have:
                die(f"{name} turns on {sorted(want - have)} of {dep}, which {dep} does not "
                    "have by default. Buck2 would verify against a different crate than Cargo.")
            if (have - want) - {"default"}:
                die(f"{name} builds {dep} without {sorted(have - want)}, which {dep} has by "
                    "default. Buck2 would verify against a different crate than Cargo.")
            if "default" in have - want:
                src = os.path.join(ROOT, info[dep]["dir"], "src")
                hit = subprocess.run(["grep", "-rlE", r'feature\s*=\s*"default"', src],
                                     capture_output=True, text=True).stdout
                if hit:
                    die(f"{dep} tests for feature \"default\", and {name} builds it without")
            vstd |= info[dep]["vstd"]
        i["vstd_all"] = frozenset(vstd)
    for name, i in sorted(info.items()):
        for dep in closure(name):
            if info[dep]["vstd_all"] != i["vstd_all"]:
                die(f"{name} needs vstd with {sorted(i['vstd_all'])} but its dependency {dep} "
                    f"is verified with {sorted(info[dep]['vstd_all'])}")

    vstd_pkg = by_name["vstd"]
    if len(vstd_pkg) != 1:
        die("more than one vstd in Cargo.lock")
    vstd_pkg = vstd_pkg[0]

    def vstd_target(feats):
        feats = frozenset(feats)
        if feats not in vstd_variants:
            label = "-".join(sorted(feats - {"default"})) or "bare"
            vstd_variants[feats] = "vstd-" + label
        return "//third-party:" + vstd_variants[feats]

    for name, i in sorted(info.items()):
        pkg = i["pkg"]
        deps = [f"//crates/{info[d]['short']}:{info[d]['short']}" for d, _ in i["deps"]]
        for dep, want in i["externs"]:
            key = dep["name"]
            if key in third_party and (third_party[key][0]["id"] != dep["id"]
                                       or third_party[key][1] != want):
                die(f"{key} is needed in two versions or with two feature sets")
            third_party[key] = (dep, want)
            deps.append(f"//third-party:{key}")
        srcs = 'glob(["src/**"])'
        extra = outside_includes(i["dir"], os.path.join(i["dir"], "src"))
        if extra:
            srcs += " + " + fmt_list(extra)
        lines = [
            HEADER,
            'load("@root//verus:defs.bzl", "verus_library")\n',
            "verus_library(",
            f'    name = "{i["short"]}",',
            f'    crate = "{i["crate"]}",',
            f'    package = "{pkg["name"]}",',
            f'    version = "{pkg["version"]}",',
            f'    edition = "{pkg["edition"]}",',
            '    crate_root = "src/lib.rs",',
            f"    srcs = {srcs},",
            f'    features = {fmt_list(sorted(i["features"]))},',
            f'    vstd = "{vstd_target(i["vstd_all"])}",',
            f"    deps = {fmt_list(sorted(deps))},",
        ]
        if i["parts"] != 1:
            lines.append(f'    parts = {i["parts"]},')
        lines += ['    visibility = ["PUBLIC"],', ")", ""]
        files[os.path.join(i["dir"], "BUCK")] = "\n".join(lines)

    def archive(pkg):
        key = (pkg["name"], pkg["version"])
        if key not in checksums:
            die(f"no checksum for {key} in Cargo.lock")
        n, v = key
        return "\n".join([
            "http_archive(",
            f'    name = "{n}-{v}.crate",',
            f'    urls = ["https://static.crates.io/crates/{n}/{n}-{v}.crate"],',
            f'    sha256 = "{checksums[key]}",',
            f'    strip_prefix = "{n}-{v}",',
            '    type = "tar.gz",',
            ")", ""])

    tp = [HEADER, 'load("@root//verus:defs.bzl", "rustc_library", "verus_vstd")\n',
          "# vstd, from the crates.io release Cargo.lock pins, once for each set of",
          "# features the verified crates ask for.",
          archive(vstd_pkg)]
    for feats, target in sorted(vstd_variants.items(), key=lambda kv: kv[1]):
        tp += [
            "verus_vstd(",
            f'    name = "{target}",',
            f'    archive = ":vstd-{vstd_pkg["version"]}.crate",',
            f'    edition = "{vstd_pkg["edition"]}",',
            f'    features = {fmt_list(sorted(feats))},',
            '    visibility = ["PUBLIC"],',
            ")", ""]
    for key, (pkg, want) in sorted(third_party.items()):
        normal = [d for d in pkg["dependencies"] if d["kind"] is None and not d["optional"]]
        if normal:
            die(f"{key} has dependencies of its own; buckify.py has not been taught those")
        if any("custom-build" in t["kind"] for t in pkg["targets"]) and \
                pkg["version"] not in REVIEWED_BUILD_SCRIPTS.get(key, ()):
            die(f"{key} {pkg['version']} has a build script. Read it, then list the version "
                "in REVIEWED_BUILD_SCRIPTS.")
        lib = lib_target(pkg)
        root = os.path.relpath(lib["src_path"], os.path.dirname(pkg["manifest_path"]))
        tp += [
            archive(pkg),
            "rustc_library(",
            f'    name = "{key}",',
            f'    crate = "{lib["name"].replace("-", "_")}",',
            f'    package = "{pkg["name"]}",',
            f'    version = "{pkg["version"]}",',
            f'    edition = "{pkg["edition"]}",',
            f'    archive = ":{key}-{pkg["version"]}.crate",',
            f'    archive_root = "{root}",',
            f'    features = {fmt_list(sorted(want))},',
            '    visibility = ["PUBLIC"],',
            ")", ""]
    files[os.path.join("third-party", "BUCK")] = "\n".join(tp)
    return files, verified


def main():
    check = "--check" in sys.argv[1:]
    files, verified = generate()
    # A BUCK file with a verus_library that this script did not write would
    # be a crate verified in some way nobody reviewed.
    stale = []
    for base, dirs, names in os.walk(os.path.join(ROOT, "crates")):
        dirs[:] = [d for d in dirs if d not in ("target", "bench", "fuzz", "compat", "node_modules")]
        if "BUCK" in names:
            rel = os.path.relpath(os.path.join(base, "BUCK"), ROOT)
            if rel not in files:
                stale.append(rel)
    bad = []
    for rel, text in sorted(files.items()):
        path = os.path.join(ROOT, rel)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            bad.append(rel)
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(text)
    if check:
        if bad or stale:
            for rel in bad:
                print(f"out of date: {rel}", file=sys.stderr)
            for rel in stale:
                print(f"not generated by buckify.py: {rel}", file=sys.stderr)
            sys.exit("buckify.py: run scripts/buckify.py and commit the result")
        print(f"buckify.py: {len(files)} files up to date, {len(verified)} verified crates")
    else:
        for rel in stale:
            os.remove(os.path.join(ROOT, rel))
        print(f"buckify.py: wrote {len(bad)} of {len(files)} files" +
              (f", removed {stale}" if stale else ""))


if __name__ == "__main__":
    main()
